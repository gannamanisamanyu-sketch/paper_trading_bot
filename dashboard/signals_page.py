"""Today's Signals: the current model portfolio and the full stock ranking."""
from __future__ import annotations

import pandas as pd
import plotly.express as px
import streamlit as st

from dashboard.common import BLUE, LIVE, load_csv, load_json, missing, paper_banner, pct, style_fig

Z_COLS = ["z_momentum", "z_trend", "z_sector", "z_quality", "z_value", "z_growth", "z_risk"]


def page() -> None:
    st.title("📡 Today's Signals")
    paper_banner()
    meta = load_json(str(LIVE / "meta.json"))
    port = load_csv(str(LIVE / "model_portfolio.csv"))
    scores = load_csv(str(LIVE / "scores.csv"), index_col=0)
    if meta is None or scores.empty:
        missing("No live signals yet. They are generated by `python main.py signals` (run automatically "
                "every weekday by the GitHub Action).")
        return

    st.caption(f"Based on closing prices of **{meta['as_of']}** · generated {meta['generated']} · "
               f"what the strategy would hold if a fresh ${meta['capital']:,.0f} portfolio started today.")
    c = st.columns(4)
    c[0].metric("Stocks in model portfolio", meta["n_positions"], border=True)
    c[1].metric("Invested", pct(meta["invested"], 0), f"{1 - meta['invested']:.0%} cash", delta_color="off", border=True)
    c[2].metric("Market regime", "Risk-on" if meta["market_risk_on"] else "Risk-off",
                "SPY above 200-day avg" if meta["market_risk_on"] else "SPY below 200-day avg → max 50% invested",
                delta_color="off", border=True)
    c[3].metric("Est. portfolio volatility", pct(meta["est_volatility"]), "target 16%", delta_color="off", border=True)
    if meta.get("notes"):
        st.caption(f"Risk overlay: {meta['notes']}")

    if len(port):
        a, b = st.columns([3, 2])
        with a:
            st.subheader("Model portfolio")
            st.dataframe(
                port[["ticker", "name", "sector", "weight", "dollars", "shares", "price", "score", "rank", "reason"]],
                hide_index=True,
                column_config={
                    "weight": st.column_config.ProgressColumn("weight", format="percent", min_value=0, max_value=0.1),
                    "dollars": st.column_config.NumberColumn("$ amount", format="$%.0f"),
                    "price": st.column_config.NumberColumn("price", format="$%.2f"),
                    "score": st.column_config.NumberColumn(format="%.2f"),
                    "shares": st.column_config.NumberColumn(format="%d"),
                })
        with b:
            sec = port.groupby("sector")["weight"].sum().reset_index()
            sec.loc[len(sec)] = ["Cash", 1 - port["weight"].sum()]
            st.plotly_chart(style_fig(px.pie(sec, names="sector", values="weight", hole=0.5), 380,
                                      "Allocation by sector"))

    st.subheader("Full ranking")
    sectors = sorted(scores["sector"].dropna().unique())
    pick = st.multiselect("Filter by sector", sectors)
    view = scores[scores["sector"].isin(pick)] if pick else scores
    st.dataframe(
        view[["name", "sector", "rank", "score", "in_model_portfolio", "momentum_12_1", "price_vs_sma200",
              "rsi", "volatility", "beta", "earnings_yield", "roe", "revenue_growth"]],
        column_config={
            "score": st.column_config.NumberColumn(format="%.2f"),
            "momentum_12_1": st.column_config.NumberColumn("12-1m momentum", format="percent"),
            "price_vs_sma200": st.column_config.NumberColumn("vs 200d avg", format="percent"),
            "rsi": st.column_config.NumberColumn("RSI", format="%.0f"),
            "volatility": st.column_config.NumberColumn("volatility", format="percent"),
            "beta": st.column_config.NumberColumn(format="%.2f"),
            "earnings_yield": st.column_config.NumberColumn("E/P", format="percent"),
            "roe": st.column_config.NumberColumn("ROE", format="percent"),
            "revenue_growth": st.column_config.NumberColumn("rev growth", format="percent"),
            "in_model_portfolio": st.column_config.CheckboxColumn("held"),
        }, height=420)

    st.subheader("Why does a stock score the way it does?")
    tk = st.selectbox("Stock", scores.index.tolist(),
                      format_func=lambda t: f"{t} · {scores.loc[t, 'name']} (rank {int(scores.loc[t, 'rank'])})")
    z = scores.loc[tk, Z_COLS].astype(float).rename(lambda c: c.replace("z_", ""))
    z["risk"] = -z["risk"]  # shown as its contribution direction (risk is a penalty)
    z = z.rename({"risk": "risk (penalty, sign flipped)"})
    fig = px.bar(x=z.values, y=z.index, orientation="h", color=z.values > 0,
                 color_discrete_map={True: "#16a34a", False: "#dc2626"})
    fig.update_layout(showlegend=False, xaxis_title="z-score (standard deviations vs. the average stock)",
                      yaxis_title="")
    st.plotly_chart(style_fig(fig, 320, f"{tk}: factor z-scores (overall score {scores.loc[tk, 'score']:.2f})"))
    st.caption("Overall score = 0.30·momentum + 0.15·trend + 0.10·sector + 0.15·quality + 0.10·value + "
               "0.10·growth − 0.10·risk. Fundamentals are compared within each sector.")
